static inline uint32_t obv_pitch_inc(int32_t pitch)
{
    if (pitch < 0) pitch = 0;
    if (pitch > 131 * 256 + 255) pitch = 131 * 256 + 255;
    unsigned note = (unsigned)pitch >> 8;
    unsigned octave = note / 12;
    uint32_t base = obv_inc_c9[note % 12];
    uint32_t fine = obv_fine_q16[pitch & 255];
    /* fine is Q16 in [65536, 69433). Split the fractional product into
     * 16-bit limbs to keep the upstream result with native 32-bit multiplies. */
    uint32_t frac = fine - 65536u;
    uint32_t whole = base + (base >> 16) * frac + (((base & 65535u) * frac) >> 16);
    return whole >> (10u - octave);
}
