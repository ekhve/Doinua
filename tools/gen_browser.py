"""The Sound Browser's list as a C header for the companion app (ST-68, D-087).

  gen_browser.py [LIST] [OUT]

LIST defaults to assets/sounds/browser.json (the owner's picks in the Sound Browser Lab's order, by group), OUT to
apps/companion/sb_data.h. Only the sounds of engines the firmware has (BUILT) go in: the others wait for their engine's
port, and adding the engine's name here brings them in. The app finds each one's engine and preset by name at start-up
(kit_engine_name, kit_preset_name), so a sound whose preset is missing is left out rather than wrong."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILT = ["Analog", "Lo-fi", "Organ wheel", "Drums", "FMini", "Juno-106", "Bass Something 2", "OberVave", "CoralFlower VA"]   # the kit's engines the picks come from (kit_engine_name)
AS = {"CoralFlower: VA": "CoralFlower VA", "CoralFlower: VA (bass)": "CoralFlower VA", "OberVave: OberVave": "OberVave", "Bass Something 2: Bass Something 2": "Bass Something 2", "FM-106: Juno-106": "Juno-106"}     # the picks' firmware and engine, where the kit's engine is named otherwise
src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "assets" / "sounds" / "browser.json"
out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "apps" / "companion" / "sb_data.h"
d = json.loads(src.read_text())
groups, short = d["groups"], d["short"]
for s in d["sounds"]:
    s["engine"] = AS.get(s["engine"], s["engine"])
rows = [s for s in d["sounds"] if s["engine"] in BUILT]


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


L = ["/* SPDX-License-Identifier: GPL-3.0-only",
     " * Generated by tools/gen_browser.py from assets/sounds/browser.json (do not edit by hand): the Sound Browser's",
     f" * sounds of the engines built ({', '.join(BUILT)}), {len(rows)} of the owner's {len(d['sounds'])} picks. */",
     f"#define SB_NGROUPS {len(groups)}",
     f"#define SB_NALL {len(rows)}",
     "static const char *const SB_GROUP[SB_NGROUPS] = { " + ", ".join(c(g) for g in groups) + " };",
     "static const char *const SB_SHORT[SB_NGROUPS] = { " + ", ".join(c(g) for g in short) + " };",
     f"static const char *const SB_ENGINE[{len(BUILT)}] = {{ " + ", ".join(c(e) for e in BUILT) + " };",
     "typedef struct { uint8_t group, engine; const char *name, *preset; } sb_entry_t;   /* engine: SB_ENGINE's */",
     "static const sb_entry_t SB_ALL[SB_NALL] = {"]
for s in rows:
    L.append(f"    {{ {groups.index(s['group'])}, {BUILT.index(s['engine'])}, {c(s['name'])}, {c(s['preset'])} }},")
L += ["};", ""]
out.write_text("\n".join(L))
print(f"browser: {len(rows)} of {len(d['sounds'])} sounds -> {out}")
