"""The synth's tables as a C header: a 1024-point sine (Q15) and each MIDI note's phase increment.

  gen_tables.py OUT.h [FS]"""
import math
import sys

out = sys.argv[1]
fs = int(sys.argv[2]) if len(sys.argv) > 2 else 44100
sine = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]
inc = [round(440.0 * 2 ** ((n - 69) / 12) / fs * 2 ** 32) & 0xFFFFFFFF for n in range(128)]
# preset envelopes (Felucca-Engines presets: A D S R as 0..127): a value's time, 1 ms .. ~4 s on a square curve;
# attack as a linear step a 32-sample block (Q24), decay / release as a per-block multiplier to -60 dB (Q16)
blocks_per_s = fs / 32
def env_time(v): return 0.001 + 4.0 * (v / 127) ** 2
env_step = [max(1, round((1 << 24) / max(1.0, env_time(v) * blocks_per_s))) for v in range(128)]
env_mul = [min(65535, round(65536 * math.exp(math.log(0.001) / max(1.0, env_time(v) * blocks_per_s)))) for v in range(128)]
# FMINI (D-086): fmini-1's tools/gen_tables.py, as it makes them: times 1 ms .. 12 s (exponential), an attack step (Q24)
# and a one-pole coefficient (Q16, -24 dB after the time) a CTL-sample block; LFO 0.05 .. 40 Hz; LEVEL (112 = 0 dB)
CTL = 32
fm_ms = [1.0 * (12000 ** (v / 127)) for v in range(128)]
fm_lin = [max(1, int((1 << 24) * CTL / (m * fs / 1000))) for m in fm_ms]
fm_exp = [max(1, min(65535, int(65536 * (1 - math.exp(-CTL / (m / 1000 / 2.8 * fs)))))) for m in fm_ms]
fm_lfo = [int(0.05 * (800 ** (v / 127)) * CTL / fs * 2 ** 32) for v in range(128)]
fm_lvl = [0] + [int(round(4096 * 10 ** (((v - 112) / 2) / 20))) for v in range(1, 128)]
with open(out, "w") as f:
    f.write("/* generated by tools/gen_tables.py: do not edit */\n#pragma once\n#include <stdint.h>\n")
    f.write(f"#define KIT_TABLE_FS {fs}\n")
    f.write("static const int16_t KIT_SINE[1025] = {\n")
    for i in range(0, 1025, 16):
        f.write("  " + ",".join(str(v) for v in sine[i:i + 16]) + ",\n")
    f.write("};\nstatic const uint32_t KIT_NOTE_INC[128] = {\n")
    for i in range(0, 128, 8):
        f.write("  " + ",".join(f"{v}u" for v in inc[i:i + 8]) + ",\n")
    f.write("};\n")
    f.write("static const uint32_t KIT_ENV_STEP[128] = {\n")
    for i in range(0, 128, 8):
        f.write("  " + ",".join(f"{v}u" for v in env_step[i:i + 8]) + ",\n")
    f.write("};\nstatic const uint16_t KIT_ENV_MUL[128] = {\n")
    for i in range(0, 128, 8):
        f.write("  " + ",".join(str(v) for v in env_mul[i:i + 8]) + ",\n")
    f.write("};\n")
    for name, ctype, vals, suf in (("FM_ENV_LIN", "uint32_t", fm_lin, "u"), ("FM_ENV_EXP", "uint16_t", fm_exp, ""),
                                   ("FM_ENV_MS", "uint16_t", [round(ms) for ms in fm_ms], ""),
                                   ("FM_LFO_INC", "uint32_t", fm_lfo, "u"),
                                   ("FM_LFO_CHZ", "uint16_t", [round(5 * 800 ** (v / 127)) for v in range(128)], ""),
                                   ("FM_LEVEL_Q12", "uint16_t", fm_lvl, "")):
        f.write(f"static const {ctype} {name}[128] = {{\n")
        for i in range(0, 128, 8):
            f.write("  " + ",".join(f"{v}{suf}" for v in vals[i:i + 8]) + ",\n")
        f.write("};\n")
print(f"tables: sine 1025, note increments 128 at {fs} Hz -> {out}")
