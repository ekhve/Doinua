"""Rasterise the kit's fonts into a C header: 4-bit alpha glyphs, sorted by code point.

  gen_font.py OUT.h

Inter Tight (SIL OFL 1.1, assets/fonts/OFL.txt). The HUGE size carries only what note names
and big numbers need, to keep flash use small. MEDIUM, LARGE and HUGE are run-length coded (D-092): a byte a run,
its alpha in the high nibble and its length less one (1..16 pixels) in the low, the glyph's pixels row after row;
their glyphs are mostly runs of empty and solid, a third to a quarter of the 4-bit pixels' size. The small sizes,
mostly edges, stay 4-bit pixels (two a byte, a row padded to a byte)."""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = ROOT / "assets" / "fonts" / "InterTight.ttf"
ASCII = "".join(chr(c) for c in range(32, 127))
HUGE_CHARS = " #b0123456789ABCDEFGLMRSadeilors?!-"
RLE = {"MEDIUM", "LARGE", "HUGE"}
FONTS = [  # (enum name, pixel size, weight, characters)
    ("SMALL", 16, 500, ASCII),
    ("MEDIUM", 24, 600, ASCII),
    ("LARGE", 40, 700, ASCII),
    ("HUGE", 96, 700, HUGE_CHARS),
    ("TINY", 10, 600, ASCII),       # API 14: labels on keys and knobs
    ("XSMALL", 13, 600, ASCII),     # API 14: quiet metadata
]


def rle(px):
    out, i = bytearray(), 0
    while i < len(px):
        j = i
        while j < len(px) and px[j] == px[i] and j - i < 16:
            j += 1
        out.append((px[i] << 4) | (j - i - 1))
        i = j
    return out


def rasterise(size, weight, chars, coded=False):
    font = ImageFont.truetype(str(TTF), size)
    try:
        font.set_variation_by_axes([weight])
    except OSError:
        pass
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in sorted(set(chars)):
        adv = round(font.getlength(ch))
        l, t, r, b = font.getbbox(ch, anchor="la")
        w, h = max(0, r - l), max(0, b - t)
        off = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="la")
            px = img.load()
            rows = [[(px[x, y] * 15 + 127) // 255 for x in range(w)] for y in range(h)]
            if coded:
                data += rle([a for row in rows for a in row])
            else:
                for row in rows:
                    if len(row) % 2:
                        row.append(0)
                    data += bytes((row[i] << 4) | row[i + 1] for i in range(0, len(row), 2))
        glyphs.append((ord(ch), w, h, l, t, adv, off))
    return ascent + descent, ascent, glyphs, data


def main():
    out = Path(sys.argv[1])
    lines = ["/* generated by tools/gen_font.py from Inter Tight (SIL OFL 1.1): do not edit */",
             "#pragma once", "#include <stdint.h>",
             "typedef struct { uint16_t cp; uint8_t w, h; int8_t xo, yo; uint8_t adv; uint32_t off; } kit_glyph_t;",
             "typedef struct { uint8_t height, ascent; uint16_t n; const kit_glyph_t *g; const uint8_t *data; uint8_t rle; } kit_font_t;"]
    total = 0
    for name, size, weight, chars in FONTS:
        height, ascent, glyphs, data = rasterise(size, weight, chars, name in RLE)
        total += len(data) + 10 * len(glyphs)
        lines.append(f"static const kit_glyph_t KIT_G_{name}[{len(glyphs)}] = {{")
        lines += [f"  {{{cp}, {w}, {h}, {xo}, {yo}, {adv}, {off}}}," for cp, w, h, xo, yo, adv, off in glyphs]
        lines.append("};")
        lines.append(f"static const uint8_t KIT_D_{name}[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        if not data:
            lines.append("  0,")
        lines.append("};")
    lines.append("static const kit_font_t KIT_FONT_DATA[] = {")
    for name, size, weight, chars in FONTS:
        height, ascent, glyphs, _ = rasterise(size, weight, chars, name in RLE)
        lines.append(f"  {{{height}, {ascent}, {len(glyphs)}, KIT_G_{name}, KIT_D_{name}, {int(name in RLE)}}},")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"fonts: {len(FONTS)} sizes, {total} B -> {out}")


if __name__ == "__main__":
    main()
