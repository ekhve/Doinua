"""Extract the selected CoralFlower VA factory presets and their patch edits.

Usage: python3 tools/gen_coralflower_va.py UPSTREAM_CHECKOUT
The generated include uses the VA engine's original preset type and patch macros.
"""
import argparse
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
REVISION = "46790b943bdb5e4143212d83dc495c832eefdbb8"
SOURCE = "firmware/src/eng_va.c"

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("upstream", type=Path)
args = parser.parse_args()
source = subprocess.check_output(
    ["git", "-C", str(args.upstream), "show", f"{REVISION}:{SOURCE}"],
    text=True,
)
preset_body = source.split("static const preset_t VA_PRESETS[] = {", 1)[1].split("};", 1)[0]
presets = re.findall(r'^\s*(\{"([^"]+)",[^\n]+\}),?$', preset_body, re.M)
edit_body = source.split("static const uint8_t *const VA_PRESET_EDITS[] = {", 1)[1].split("};", 1)[0]
symbols = re.findall(r"VAP_\w+", edit_body)
edits = dict(re.findall(r"static const uint8_t (VAP_\w+)\[\] = (\{[^}]+\});", source))
if len(presets) != len(symbols) or not presets:
    parser.error("upstream preset and edit tables do not match")

chosen = []
used_slots = set()
for line in (ROOT / "assets/sounds/coralflower-va.txt").read_text().splitlines():
    if not line.strip() or line.startswith("#"):
        continue
    field, name = line.split(maxsplit=1)
    slot = int(field)
    if not 0 <= slot < len(presets) or slot in used_slots or name != presets[slot][1]:
        parser.error(f"invalid or duplicate selection {line!r}")
    used_slots.add(slot)
    chosen.append(slot)

lines = [
    "/* SPDX-License-Identifier: GPL-3.0-only",
    " * Copyright (C) 2026 ChoralRoot FM-1 contributors (a fork of Felucca)",
    f" * Generated by tools/gen_coralflower_va.py from CoralFlower {REVISION[:7]}. */",
    "#pragma once",
    "",
]
for symbol in dict.fromkeys(symbols[slot] for slot in chosen):
    lines.append(f"static const uint8_t {symbol}[] = {edits[symbol]};")
lines.extend(["", "static const preset_t VA_PRESETS[] = {"])
lines.extend(f"    {presets[slot][0]}," for slot in chosen)
lines.extend(["};", "static const uint8_t *const VA_PRESET_EDITS[] = {"])
lines.extend(f"    {symbols[slot]}," for slot in chosen)
lines.extend(["};", ""])
(ROOT / "fm1kit/src/coralflower/va_bank.h").write_text("\n".join(lines))
