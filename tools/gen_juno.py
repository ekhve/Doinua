"""FM-106's (Juno-106) factory presets that the owner picked, as a C header for fm1kit's Juno (D-090).

  gen_juno.py FM106_SRC_DIR [PICKS] [OUT]

FM106_SRC_DIR is FM-106's firmware/src (https://github.com/PatttF/fm-106, GPL-3.0-only); PICKS defaults to
assets/sounds/juno.txt (a preset number and its name a line), OUT to fm1kit/src/juno/juno_bank.h. Each pick's preset
(its name and 66 bytes) is copied as it is, and its name checked."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1])
picks = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "assets" / "sounds" / "juno.txt"
out = Path(sys.argv[3]) if len(sys.argv) > 3 else ROOT / "fm1kit" / "src" / "juno" / "juno_bank.h"
text = (src / "fm106_presets.h").read_text()
body = text[text.index("FM106_PRESETS[FM106_NUM_FACTORY_PRESETS] = {"):]
rows = re.findall(r'^\s*(\{"([^"]*)",\s*\{[^}]*\}\}),?\s*$', body, re.M)
assert len(rows) >= 128, len(rows)
want = []
for ln in picks.read_text().splitlines():
    if ln.strip() and not ln.startswith("#"):
        n, name = ln.split(None, 1)
        want.append((int(n), name.strip()))
L = ["/* SPDX-License-Identifier: GPL-3.0-only",
     " * Generated by tools/gen_juno.py (do not edit by hand) from FM-106's fm106_presets.h (https://github.com/PatttF/fm-106,",
     " * GPL-3.0-only; decoded from the Juno-106 SysEx library): the owner's picks, assets/sounds/juno.txt. */",
     f"#define JUNO_N {len(want)}", "static const fm106_preset_t JUNO_PICKS[JUNO_N] = {"]
for n, name in want:
    row, full = rows[n]
    assert full[4:].strip() == name, (n, name, full)
    L.append(f"    {row},")
L += ["};", ""]
out.write_text("\n".join(L))
print(f"juno: {len(want)} presets -> {out}")
