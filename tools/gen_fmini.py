"""FMini-1's factory patches that the owner picked, as a C header for fm1kit's FMini engine (ST-70, D-086).

  gen_fmini.py FMINI_SRC_DIR [PICKS] [OUT]

FMINI_SRC_DIR is fmini-1's firmware/src (https://github.com/ruppert/fmini-1, GPL-3.0-only); PICKS defaults to
assets/sounds/fmini.txt (a factory number and its name a line), OUT to fm1kit/src/fmini/fmini_bank.h. For each pick it
copies the patch's 32 bytes (FMINI_FACTORY), its preset (FMINI_PRESETS: knobs, envelope, mono, sends) and its extras
(FMINI_X: LFO, FX, level, modulation, octave) as they are, and checks the name."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1])
picks = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "assets" / "sounds" / "fmini.txt"
out = Path(sys.argv[3]) if len(sys.argv) > 3 else ROOT / "fm1kit" / "src" / "fmini" / "fmini_bank.h"

text = (src / "eng_fmini_presets.h").read_text()


def block(start):
    i = text.index(start)
    j = text.index("\n};", i)
    return text[text.index("{", i + len(start) - 1) + 1:j]


fact = re.findall(r"^\s*(FGP\([^)]*\)),\s*/\*\s*(\d+)\s+(.+?)\s*\*/", block("FMINI_FACTORY[FMINI_NFACTORY][FG_SIZE] = {"), re.M)
pres = re.findall(r'^\s*(\{"[^"]+".*\}),\s*$', block("FMINI_PRESETS[] = {"), re.M)
xs = re.findall(r"^\s*(\{\{.*\}),\s*/\*\s*(\d+)\s*\*/", block("FMINI_X[FMINI_NFACTORY] = {"), re.M)
assert len(fact) == len(pres) == len(xs) == 200, (len(fact), len(pres), len(xs))

want = []
for ln in picks.read_text().splitlines():
    if ln.strip() and not ln.startswith("#"):
        n, name = ln.split(None, 1)
        want.append((int(n), name.strip()))

L = ["/* SPDX-License-Identifier: GPL-3.0-only",
     " * Generated by tools/gen_fmini.py (do not edit by hand) from fmini-1's eng_fmini_presets.h (https://github.com/ruppert/fmini-1,",
     " * GPL-3.0-only, by its authors): the owner's picks of its factory patches, assets/sounds/fmini.txt. */",
     f"#define FMB_N {len(want)}", "",
     "static const uint8_t FMB_PATCH[FMB_N][FG_SIZE] = {"]
for n, name in want:
    fn, fname = int(fact[n][1]), fact[n][2]
    assert fn == n and fname == name, (n, name, fn, fname)
    L.append(f"    {fact[n][0]},   /* {n:03d} {name} */")
L += ["};", "", "static const preset_t FMB_PRE[FMB_N] = {"]
for n, name in want:
    assert pres[n].startswith('{"' + name + '"'), (n, name, pres[n][:30])
    L.append(f"    {pres[n]},")
L += ["};", "", "static const fmini_x_t FMB_X[FMB_N] = {"]
for n, name in want:
    assert int(xs[n][1]) == n
    L.append(f"    {xs[n][0]},   /* {n:03d} */")
L += ["};", ""]
out.write_text("\n".join(L))
print(f"fmini: {len(want)} patches -> {out}")
