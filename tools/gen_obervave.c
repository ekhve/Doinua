/* Generate the selected bank using OberVave's own factory loader.
 * cc -std=c11 -I/path/to/obervave/firmware/src tools/gen_obervave.c -o /tmp/gen_obervave
 * /tmp/gen_obervave < assets/sounds/obervave.txt > fm1kit/src/obervave/bank.h
 * Upstream: zvenson/obervave, a1f660c. */
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "obv_params.h"
#include "obv_patches.h"

int main(void)
{
    char line[128], name[64];
    unsigned program;
    unsigned char seen[NFACT + NVIBE] = {0};

    puts("/* SPDX-License-Identifier: GPL-3.0-only */");
    puts("/* Generated by tools/gen_obervave.c from zvenson/obervave at a1f660c. */");
    printf("static const struct { const char *name; uint8_t param[%u]; } obervave_bank[] = {\n",
           (unsigned)NPARAM);
    while (fgets(line, sizeof line, stdin)) {
        if (line[0] == '#' || line[0] == '\n') continue;
        if (sscanf(line, "%u %63[^\r\n]", &program, name) != 2 ||
            program == 0 || program > NFACT + NVIBE || seen[program - 1]) {
            fprintf(stderr, "Invalid or duplicate factory slot: %s", line);
            return 1;
        }
        seen[program - 1] = 1;
        const factory_t *factory = program <= NFACT ? &FACTORY[program - 1] :
                                                     &FACT_VIBE[program - NFACT - 1];
        if (strcmp(name, factory->name) != 0) {
            fprintf(stderr, "Program %u is %s, expected %s\n", program, factory->name, name);
            return 1;
        }
        patch_t patch;
        patch_from_factory(&patch, factory);
        printf("    {\"%s\", {", name);
        for (unsigned i = 0; i < NPARAM; ++i)
            printf("%s%u", i ? ", " : "", (unsigned)patch.v[i]);
        puts("}},");
    }
    puts("};");
    return ferror(stdin) || fflush(stdout) == EOF;
}
